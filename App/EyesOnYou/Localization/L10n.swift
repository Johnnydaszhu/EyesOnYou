// MARK: - Language preference

/// User-facing language choice. `.system` follows macOS preferred languages.
public enum AppLanguage: String, CaseIterable, Identifiable, Codable, Sendable {
    case system
    case english
    case chineseSimplified
    case chineseTraditional
    case japanese
    case korean
    case french
    case german
    case spanish

    public var id: String { rawValue }

    /// Resolved BCP-47 code used for lookups.
    public func resolvedCode(systemLanguages: [String] = Locale.preferredLanguages) -> String {
        switch self {
        case .english:
            return "en"
        case .chineseSimplified:
            return "zh-Hans"
        case .chineseTraditional:
            return "zh-Hant"
        case .japanese:
            return "ja"
        case .korean:
            return "ko"
        case .french:
            return "fr"
        case .german:
            return "de"
        case .spanish:
            return "es"
        case .system:
            return Self.resolveSystemCode(systemLanguages)
        }
    }

    /// Map macOS preferred language tags to a supported catalog code.
    public static func resolveSystemCode(_ systemLanguages: [String]) -> String {
        for tag in systemLanguages {
            let lower = tag.lowercased()
            if lower.hasPrefix("zh-hant") || lower.hasPrefix("zh-tw") || lower.hasPrefix("zh-hk") || lower.hasPrefix("zh-mo") {
                return "zh-Hant"
            }
            if lower.hasPrefix("zh") {
                return "zh-Hans"
            }
            if lower.hasPrefix("ja") { return "ja" }
            if lower.hasPrefix("ko") { return "ko" }
            if lower.hasPrefix("fr") { return "fr" }
            if lower.hasPrefix("de") { return "de" }
            if lower.hasPrefix("es") { return "es" }
            if lower.hasPrefix("en") { return "en" }
        }
        return "en"
    }

    public var settingsLabelKey: String {
        switch self {
        case .system: return "lang.system"
        case .english: return "lang.english"
        case .chineseSimplified: return "lang.chinese"
        case .chineseTraditional: return "lang.chineseTraditional"
        case .japanese: return "lang.japanese"
        case .korean: return "lang.korean"
        case .french: return "lang.french"
        case .german: return "lang.german"
        case .spanish: return "lang.spanish"
        }
    }
}

// MARK: - Store

@MainActor
final class LocalizationStore: ObservableObject {
    static let shared = LocalizationStore()

    private static let preferenceKey = "eyesonyou.languagePreference"

    /// User preference (System / English / 简体中文 / …).
    @Published var preference: AppLanguage {
        didSet {
            UserDefaults.standard.set(preference.rawValue, forKey: Self.preferenceKey)
            refreshResolved()
        }
    }

    /// Active catalog code after resolving `.system`.
    @Published private(set) var resolvedCode: String = "en"

    /// Bumps when language changes so SwiftUI views refresh.
    @Published private(set) var revision: UInt64 = 0

    init() {
        if let raw = UserDefaults.standard.string(forKey: Self.preferenceKey),
           let pref = AppLanguage(rawValue: raw) {
            preference = pref
        } else {
            preference = .system
        }
        refreshResolved()
    }

    func setPreference(_ language: AppLanguage) {
        preference = language
    }

    /// Translate a key; falls back to English then the key itself.
    func t(_ key: String) -> String {
        if let value = Self.tables[resolvedCode]?[key] { return value }
        if let value = Self.tables["en"]?[key] { return value }
        return key
    }

    /// Format helper with one string argument.
    func t(_ key: String, _ arg: CVarArg) -> String {
        String(format: t(key), arg)
    }

    private func refreshResolved() {
        resolvedCode = preference.resolvedCode()
        revision &+= 1
        objectWillChange.send()
    }

